package builtins

import "testing"

func TestDecodePowerShellOutput(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		name   string
		output []byte
		want   string
	}{
		{
			name:   "utf16 little endian BOM unicode",
			output: []byte{0xff, 0xfe, 0x1f, 0x04, 0x40, 0x04, 0x38, 0x04, 0x32, 0x04, 0x35, 0x04, 0x42, 0x04, 0x20, 0x00, 0x3d, 0xd8, 0x00, 0xde, 0x0a, 0x00},
			want:   "Привет 😀\n",
		},
		{
			name:   "utf16 big endian BOM unicode",
			output: []byte{0xfe, 0xff, 0x04, 0x1f, 0x04, 0x40, 0x04, 0x38, 0x04, 0x32, 0x04, 0x35, 0x04, 0x42, 0x00, 0x20, 0xd8, 0x3d, 0xde, 0x00, 0x00, 0x0a},
			want:   "Привет 😀\n",
		},
		{
			name:   "utf16 little endian no BOM",
			output: []byte{'h', 0, 'e', 0, 'l', 0, 'l', 0, 'o', 0, '\n', 0},
			want:   "hello\n",
		},
		{
			name:   "utf16 little endian no BOM non ASCII",
			output: []byte{0x1f, 0x04, 0x40, 0x04, 0x38, 0x04, 0x32, 0x04, 0x35, 0x04, 0x42, 0x04, 0x20, 0x00, 0x71, 0x67, 0xac, 0x4e, 0x20, 0x00, 0x3d, 0xd8, 0x00, 0xde, 0x0a, 0x00},
			want:   "Привет 東京 😀\n",
		},
		{
			name:   "utf16 big endian no BOM non ASCII",
			output: []byte{0x04, 0x1f, 0x04, 0x40, 0x04, 0x38, 0x04, 0x32, 0x04, 0x35, 0x04, 0x42, 0x00, 0x20, 0x67, 0x71, 0x4e, 0xac, 0x00, 0x20, 0xd8, 0x3d, 0xde, 0x00, 0x00, 0x0a},
			want:   "Привет 東京 😀\n",
		},
		{
			name:   "utf8 is unchanged",
			output: []byte("Привет 😀\n"),
			want:   "Привет 😀\n",
		},
		{
			name:   "utf8 BOM is stripped",
			output: append([]byte{0xef, 0xbb, 0xbf}, []byte("Привет 😀\n")...),
			want:   "Привет 😀\n",
		},
		{
			name:   "utf8 BOM ascii",
			output: []byte{0xef, 0xbb, 0xbf, 'h', 'e', 'l', 'l', 'o'},
			want:   "hello",
		},
		{
			name:   "utf8 BOM only",
			output: []byte{0xef, 0xbb, 0xbf},
			want:   "",
		},
		{
			name:   "binary-like data is unchanged",
			output: []byte{0x01, 0x00, 0x02, 0x00},
			want:   "\x01\x00\x02\x00",
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if got := decodePowerShellOutput(tt.output); got != tt.want {
				t.Errorf("decodePowerShellOutput(%x) = %q, want %q", tt.output, got, tt.want)
			}
		})
	}
}
